using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace MIA.Padezh.RulesGen;

/// <summary>
/// Генератор: читает data/rules.json и data/gender.json (формат petrovich-rules, MIT)
/// и создаёт src/MIA.Padezh/Generated/RulesTable.g.cs — правила, скомпилированные в код.
/// Благодаря этому основная библиотека не парсит JSON в рантайме и не тянет зависимостей.
/// </summary>
internal static class Program
{
    private static int Main(string[] args)
    {
        var root = args.Length > 0 ? Directory.GetCurrentDirectory() : FindRepoRoot();
        var rulesPath = args.Length > 0 ? args[0] : Path.Combine(root, "data", "rules.json");
        var genderPath = args.Length > 1 ? args[1] : Path.Combine(root, "data", "gender.json");
        var outputPath = args.Length > 2 ? args[2] : Path.Combine(root, "src/MIA.Padezh/Generated/RulesTable.g.cs");

        var options = new JsonSerializerOptions
        {
            PropertyNameCaseInsensitive = true,
            ReadCommentHandling = JsonCommentHandling.Skip,
            AllowTrailingCommas = true,
        };

        var rules = JsonSerializer.Deserialize<RulesRoot>(File.ReadAllText(rulesPath), options)
            ?? throw new InvalidDataException($"Не удалось разобрать {rulesPath}.");
        var gender = JsonSerializer.Deserialize<GenderRoot>(File.ReadAllText(genderPath), options)
            ?? throw new InvalidDataException($"Не удалось разобрать {genderPath}.");

        var dataDir = Path.GetDirectoryName(Path.GetFullPath(rulesPath))!;
        var pluralPath = Path.Combine(dataDir, "plural.json");
        var genderNamesPath = Path.Combine(dataDir, "gender-names.json");
        var plural = File.Exists(pluralPath)
            ? JsonSerializer.Deserialize<PluralRoot>(File.ReadAllText(pluralPath), options)
            : null;
        var genderNames = File.Exists(genderNamesPath)
            ? JsonSerializer.Deserialize<GenderNamesRoot>(File.ReadAllText(genderNamesPath), options)
            : null;

        var code = Generate(rules, gender, plural, genderNames);
        var outputDir = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrEmpty(outputDir))
            Directory.CreateDirectory(outputDir);

        File.WriteAllText(outputPath, code, new UTF8Encoding(false));
        Console.WriteLine($"Сгенерирован: {outputPath}");
        Console.WriteLine($"Правил: фамилии {Count(rules.Lastname)}, имена {Count(rules.Firstname)}, отчества {Count(rules.Middlename)}.");
        return 0;
    }

    private static string FindRepoRoot()
    {
        var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
        while (dir is not null
               && !File.Exists(Path.Combine(dir.FullName, "MIA.Padezh.slnx"))
               && !File.Exists(Path.Combine(dir.FullName, "MIA.Padezh.sln")))
        {
            dir = dir.Parent;
        }

        if (dir is null)
            throw new InvalidOperationException("Не найден корень репозитория (файл MIA.Padezh.slnx).");

        return dir.FullName;
    }

    private static int Count(RuleSetDto? set) => (set?.Exceptions?.Count ?? 0) + (set?.Suffixes?.Count ?? 0);

    // --- Генерация кода ----------------------------------------------------

    private static string Generate(RulesRoot rules, GenderRoot gender, PluralRoot? plural, GenderNamesRoot? genderNames)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("// Сгенерировано инструментом tools/MIA.Padezh.RulesGen из data/rules.json, data/gender.json,");
        sb.AppendLine("// data/plural.json (множественное число) и data/gender-names.json (словарь пола имён).");
        sb.AppendLine("// Источник правил: https://github.com/petrovich/petrovich-rules (MIT).");
        sb.AppendLine("// Не редактируйте вручную: правьте data/*.json и перегенерируйте.");
        sb.AppendLine();
        sb.AppendLine("namespace MIA.Padezh.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Правила склонения и определения рода (данные, скомпилированные в код).</summary>");
        sb.AppendLine("    internal static class RulesTable");
        sb.AppendLine("    {");

        EmitRuleSet(sb, "LastName", rules.Lastname);
        EmitRuleSet(sb, "FirstName", rules.Firstname);
        EmitRuleSet(sb, "MiddleName", rules.Middlename);

        var genderParts = gender.Gender ?? throw new InvalidDataException("gender.json: нет раздела \"gender\".");
        EmitGenderPart(sb, "LastName", Get(genderParts, "lastname"));
        EmitGenderPart(sb, "FirstName", Get(genderParts, "firstname"));
        EmitGenderPart(sb, "MiddleName", Get(genderParts, "middlename"));

        EmitPlural(sb, plural?.Lastname, "LastName");
        EmitPlural(sb, plural?.Firstname, "FirstName");
        EmitPlural(sb, plural?.Middlename, "MiddleName");
        EmitGenderNames(sb, genderNames);

        EmitAccessors(sb);

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static Dictionary<string, GenderRuleDto>? Get(Dictionary<string, Dictionary<string, GenderRuleDto>> map, string key)
        => map.TryGetValue(key, out var value) ? value : null;

    private static void EmitRuleSet(StringBuilder sb, string part, RuleSetDto? set)
    {
        EmitRules(sb, part + "Exceptions", set?.Exceptions, part);
        EmitRules(sb, part + "Suffixes", set?.Suffixes, part);
    }

    private static void EmitRules(StringBuilder sb, string field, List<RuleDto>? list, string part)
    {
        sb.Append("        public static readonly MIA.Padezh.RuleEntry[] ").Append(field).Append(" = new MIA.Padezh.RuleEntry[]");
        if (list is null || list.Count == 0)
        {
            sb.AppendLine(" { };");
            sb.AppendLine();
            return;
        }

        sb.AppendLine();
        sb.AppendLine("        {");
        for (int i = 0; i < list.Count; i++)
        {
            var rule = list[i];
            var gender = EmitGenderLiteral(rule.Gender, $"{field}[{i}]");
            var mods = ValidateMods(rule.Mods, $"{field}[{i}]");

            sb.Append("            new(");
            sb.Append(LitArray(rule.Test ?? new List<string>())).Append(", ");
            sb.Append(LitArray(mods)).Append(", ");
            sb.Append(rule.Tags is { Count: > 0 } ? LitArray(rule.Tags) : "null").Append(", ");
            sb.Append(gender).AppendLine("),");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static string EmitGenderLiteral(string? gender, string context) => gender switch
    {
        "male" => "MIA.Padezh.Gender.Male",
        "female" => "MIA.Padezh.Gender.Female",
        "androgynous" => "MIA.Padezh.Gender.Androgynous",
        _ => throw new InvalidDataException($"{context}: неизвестный род \"{gender}\"."),
    };

    private static List<string> ValidateMods(List<string>? mods, string context)
    {
        if (mods is null || mods.Count == 0)
            throw new InvalidDataException($"{context}: нет модификаторов падежей.");
        if (mods.Count != 5)
            throw new InvalidDataException($"{context}: ожидалось 5 модификаторов (РД, ДТ, ВН, ТВ, ПР), найдено {mods.Count}.");
        return mods;
    }

    private static void EmitGenderPart(StringBuilder sb, string part, Dictionary<string, GenderRuleDto>? kinds)
    {
        GenderRuleDto? exceptions = null, suffixes = null;
        if (kinds is not null)
        {
            kinds.TryGetValue("exceptions", out exceptions);
            kinds.TryGetValue("suffixes", out suffixes);
        }

        EmitGenderSet(sb, part + "GenderExceptions", exceptions);
        EmitGenderSet(sb, part + "GenderSuffixes", suffixes);
    }

    /// <summary>Массив из трёх списков [муж., жен., андрогинный]; null — если раздела нет вовсе.</summary>
    private static void EmitGenderSet(StringBuilder sb, string field, GenderRuleDto? rule)
    {
        sb.Append("        public static readonly string[][]? ").Append(field).Append(" = ");
        if (rule is null)
        {
            sb.AppendLine("null;");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("new string[][]");
        sb.AppendLine("        {");
        sb.Append("            ").AppendLine(LitArray(rule.Male ?? new List<string>()) + ",");
        sb.Append("            ").AppendLine(LitArray(rule.Female ?? new List<string>()) + ",");
        sb.Append("            ").AppendLine(LitArray(rule.Androgynous ?? new List<string>()));
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitPlural(StringBuilder sb, PluralRuleSetDto? set, string part)
    {
        var rules = set?.Suffixes ?? new List<RuleDto>();
        sb.AppendLine("        /// <summary>Правила множественного числа (6 модификаторов: Им., Род., Дат., Вин., Твор., Предл.).</summary>");
        sb.AppendLine("        public static readonly MIA.Padezh.PluralEntry[] " + part + "Plural = new MIA.Padezh.PluralEntry[]");
        if (rules.Count == 0)
        {
            sb.AppendLine("        { };");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("        {");
        for (int i = 0; i < rules.Count; i++)
        {
            var rule = rules[i];
            var gender = EmitGenderLiteral(rule.Gender, $"{part}Plural[{i}]");
            if (rule.Mods is null || rule.Mods.Count != 6)
                throw new InvalidDataException($"{part}Plural[{i}]: ожидалось 6 модификаторов, найдено {rule.Mods?.Count ?? 0}.");

            sb.Append("            new(");
            sb.Append(LitArray(rule.Test ?? new List<string>())).Append(", ");
            sb.Append(LitArray(rule.Mods)).Append(", ");
            sb.Append(gender).AppendLine("),");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static void EmitGenderNames(StringBuilder sb, GenderNamesRoot? genderNames)
    {
        sb.AppendLine("        /// <summary>Словарь пола имён (нижний регистр, отсортирован для бинарного поиска).</summary>");
        var male = genderNames?.Male ?? new List<string>();
        var female = genderNames?.Female ?? new List<string>();
        var andro = genderNames?.Androgynous ?? new List<string>();

        EmitSortedNameList(sb, "GenderNameMale", male);
        EmitSortedNameList(sb, "GenderNameFemale", female);
        EmitSortedNameList(sb, "GenderNameAndrogynous", andro);
    }

    private static void EmitSortedNameList(StringBuilder sb, string field, IEnumerable<string> names)
    {
        var sorted = names.Select(n => n.ToLowerInvariant()).Distinct().OrderBy(n => n, StringComparer.Ordinal).ToArray();
        sb.Append("        public static readonly string[] ").Append(field).Append(" = new string[] { ");
        sb.Append(string.Join(", ", sorted.Select(Lit)));
        sb.AppendLine(" };");
        sb.AppendLine();
    }

    private static void EmitAccessors(StringBuilder sb)
    {
        sb.AppendLine("        public static MIA.Padezh.RuleEntry[] Exceptions(MIA.Padezh.NamePart part)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (part)");
        sb.AppendLine("            {");
        sb.AppendLine("                case MIA.Padezh.NamePart.FirstName: return FirstNameExceptions;");
        sb.AppendLine("                case MIA.Padezh.NamePart.LastName: return LastNameExceptions;");
        sb.AppendLine("                default: return MiddleNameExceptions;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static MIA.Padezh.RuleEntry[] Suffixes(MIA.Padezh.NamePart part)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (part)");
        sb.AppendLine("            {");
        sb.AppendLine("                case MIA.Padezh.NamePart.FirstName: return FirstNameSuffixes;");
        sb.AppendLine("                case MIA.Padezh.NamePart.LastName: return LastNameSuffixes;");
        sb.AppendLine("                default: return MiddleNameSuffixes;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static string[][]? GenderExceptions(MIA.Padezh.NamePart part)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (part)");
        sb.AppendLine("            {");
        sb.AppendLine("                case MIA.Padezh.NamePart.FirstName: return FirstNameGenderExceptions;");
        sb.AppendLine("                case MIA.Padezh.NamePart.LastName: return LastNameGenderExceptions;");
        sb.AppendLine("                default: return MiddleNameGenderExceptions;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static string[][]? GenderSuffixes(MIA.Padezh.NamePart part)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (part)");
        sb.AppendLine("            {");
        sb.AppendLine("                case MIA.Padezh.NamePart.FirstName: return FirstNameGenderSuffixes;");
        sb.AppendLine("                case MIA.Padezh.NamePart.LastName: return LastNameGenderSuffixes;");
        sb.AppendLine("                default: return MiddleNameGenderSuffixes;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    private static string LitArray(List<string> values)
    {
        if (values.Count == 0)
            return "new string[] { }";

        var parts = new string[values.Count];
        for (int i = 0; i < values.Count; i++)
            parts[i] = Lit(values[i]);

        return "new string[] { " + string.Join(", ", parts) + " }";
    }

    private static string Lit(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    // --- DTO для разбора upstream-формата ---------------------------------

    private sealed class RuleDto
    {
        [JsonPropertyName("gender")] public string? Gender { get; set; }
        [JsonPropertyName("test")] public List<string>? Test { get; set; }
        [JsonPropertyName("mods")] public List<string>? Mods { get; set; }
        [JsonPropertyName("tags")] public List<string>? Tags { get; set; }
    }

    private sealed class RuleSetDto
    {
        [JsonPropertyName("exceptions")] public List<RuleDto>? Exceptions { get; set; }
        [JsonPropertyName("suffixes")] public List<RuleDto>? Suffixes { get; set; }
    }

    private sealed class RulesRoot
    {
        [JsonPropertyName("lastname")] public RuleSetDto? Lastname { get; set; }
        [JsonPropertyName("firstname")] public RuleSetDto? Firstname { get; set; }
        [JsonPropertyName("middlename")] public RuleSetDto? Middlename { get; set; }
    }

    private sealed class GenderRuleDto
    {
        [JsonPropertyName("male")] public List<string>? Male { get; set; }
        [JsonPropertyName("female")] public List<string>? Female { get; set; }
        [JsonPropertyName("androgynous")] public List<string>? Androgynous { get; set; }
    }

    private sealed class GenderRoot
    {
        [JsonPropertyName("gender")] public Dictionary<string, Dictionary<string, GenderRuleDto>>? Gender { get; set; }
    }

    private sealed class PluralRuleSetDto
    {
        [JsonPropertyName("exceptions")] public List<RuleDto>? Exceptions { get; set; }
        [JsonPropertyName("suffixes")] public List<RuleDto>? Suffixes { get; set; }
    }

    private sealed class PluralRoot
    {
        [JsonPropertyName("lastname")] public PluralRuleSetDto? Lastname { get; set; }
        [JsonPropertyName("firstname")] public PluralRuleSetDto? Firstname { get; set; }
        [JsonPropertyName("middlename")] public PluralRuleSetDto? Middlename { get; set; }
    }

    private sealed class GenderNamesRoot
    {
        [JsonPropertyName("male")] public List<string>? Male { get; set; }
        [JsonPropertyName("female")] public List<string>? Female { get; set; }
        [JsonPropertyName("androgynous")] public List<string>? Androgynous { get; set; }
    }
}
